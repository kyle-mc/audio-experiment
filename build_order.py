import glob
import json
import os
import sys
import tempfile
import time

from gtts import gTTS
from gtts.tts import gTTSError
from pydub import AudioSegment
import eyed3

JSON_DIR = "json"
AUDIO_DIR = "audio"
IMAGES_DIR = "images"

# Seconds of silence appended after the last spoken step.
TRAILING_BUFFER_SECONDS = 5

# gTTS occasionally returns a transient "200 OK" decode failure; a short retry
# clears it without babysitting a multi-minute batch run.
TTS_RETRIES = 3
TTS_RETRY_DELAY_SECONDS = 2


def save_tts(text, path):
    for attempt in range(1, TTS_RETRIES + 1):
        try:
            gTTS(text).save(path)
            return
        except gTTSError:
            if attempt == TTS_RETRIES:
                raise
            time.sleep(TTS_RETRY_DELAY_SECONDS)


def load_build_orders(json_dir=JSON_DIR, build_id=None):
    paths = sorted(glob.glob(os.path.join(json_dir, "*.json")))
    if build_id:
        paths = [p for p in paths if os.path.splitext(os.path.basename(p))[0] == build_id]
        if not paths:
            raise SystemExit(f"No json/{build_id}.json found")

    builds = []
    for path in paths:
        with open(path, "r", encoding="utf-8") as f:
            builds.append(json.load(f))
    return builds


def create_build_order(build, audio_dir=AUDIO_DIR, images_dir=IMAGES_DIR):
    build_id = build["id"]
    title = build["title"]
    game_speed = build["game_speed"]
    steps = build["steps"]
    cover_art = build.get("cover_art")

    os.makedirs(audio_dir, exist_ok=True)

    last_time = max(step["time"] for step in steps)
    duration_ms = int((last_time / game_speed + TRAILING_BUFFER_SECONDS) * 1000)
    full_track = AudioSegment.silent(duration=duration_ms)

    with tempfile.TemporaryDirectory(prefix=f"aoe2-build-{build_id}-") as tmp_dir:
        for step in steps:
            tmp_path = os.path.join(tmp_dir, f"{step['time']}.mp3")
            save_tts(step["text"], tmp_path)

            clip = AudioSegment.from_mp3(tmp_path)
            position_ms = int((step["time"] / game_speed) * 1000)
            full_track = full_track.overlay(clip, position=position_ms)

    output_file = os.path.join(audio_dir, f"{build_id}.mp3")
    full_track.export(output_file, format="mp3")
    print(f"[OK] Audio exported to {output_file}")

    audiofile = eyed3.load(output_file)
    if audiofile.tag is None:
        audiofile.initTag()

    audiofile.tag.title = f"AOE2 {title} Build Order"
    audiofile.tag.artist = "Generated by gTTS + pydub"
    audiofile.tag.album = "AOE2 Audio Guides"
    audiofile.tag.comments.set("Timestamps adjusted for in-game speed")

    if cover_art:
        cover_path = os.path.join(images_dir, cover_art)
        if os.path.isfile(cover_path):
            mime = "image/png" if cover_path.lower().endswith(".png") else "image/jpeg"
            with open(cover_path, "rb") as img:
                audiofile.tag.images.set(3, img.read(), mime)  # 3 = front cover
        else:
            print(f"[!] Cover art {cover_path} not found, skipping")

    audiofile.tag.save(version=eyed3.id3.ID3_V2_3)
    print(f"[OK] Metadata embedded for {build_id}")


if __name__ == "__main__":
    requested_id = sys.argv[1] if len(sys.argv) > 1 else None
    for build in load_build_orders(build_id=requested_id):
        create_build_order(build)
